"""
Model registry — catalog of all 464 DeepVRegulome fine-tuned DNABERT models.

All models live in a single HuggingFace repo (duttaprat/DeepVRegulome)
under models/<NAME>/ subfolders.
"""

from dataclasses import dataclass
from typing import Dict, List, Optional


HF_REPO = "duttaprat/DeepVRegulome"


@dataclass
class ModelInfo:
    """Metadata for a single fine-tuned DNABERT model."""
    name: str
    model_type: str       # "TF" or "HISTONE"
    accuracy: float
    f1: float
    roc_auc: float
    pr_auc: float
    peak_count: int

    @property
    def hf_repo(self) -> str:
        return HF_REPO

    @property
    def subfolder(self) -> str:
        return f"models/{self.name}"

    @property
    def input_length(self) -> int:
        return 90 if self.model_type == "SPLICE" else 301


class ModelRegistry:
    """
    Registry of all available DeepVRegulome models.

    Usage:
        registry = ModelRegistry()
        print(len(registry))                    # 462
        info = registry.get("CTCFL")            # ModelInfo
        tf_models = registry.list("TF")         # List[ModelInfo]
        names = registry.search("ZNF")          # List[str] matching prefix
    """

    def __init__(self):
        self._models: Dict[str, ModelInfo] = {}
        self._build()

    def _build(self):
        """Register all 462 models."""
        for name, mtype, acc, f1, roc, pr, peaks in _MODEL_DATA:
            self._models[name] = ModelInfo(
                name=name, model_type=mtype,
                accuracy=acc, f1=f1, roc_auc=roc, pr_auc=pr,
                peak_count=peaks,
            )

    def get(self, name: str) -> ModelInfo:
        """Get model info by exact name."""
        if name not in self._models:
            # Try case-insensitive
            for k in self._models:
                if k.lower() == name.lower():
                    return self._models[k]
            close = self.search(name[:4]) if len(name) >= 4 else []
            hint = f" Did you mean: {', '.join(close[:5])}?" if close else ""
            raise KeyError(f"Model '{name}' not found.{hint}")
        return self._models[name]

    def list(self, model_type: Optional[str] = None) -> List[ModelInfo]:
        """List all models, optionally filtered by type ('TF', 'HISTONE', or 'SPLICE')."""
        models = list(self._models.values())
        if model_type:
            mt = model_type.upper()
            models = [m for m in models if m.model_type == mt]
        return sorted(models, key=lambda m: (-m.roc_auc, m.name))

    def search(self, query: str) -> List[str]:
        """Search model names by prefix or substring."""
        q = query.upper()
        return sorted(n for n in self._models if q in n.upper())

    @property
    def names(self) -> List[str]:
        return sorted(self._models.keys())

    def __contains__(self, name: str) -> bool:
        return name in self._models

    def __len__(self) -> int:
        return len(self._models)

    def __repr__(self) -> str:
        tf = sum(1 for m in self._models.values() if m.model_type == "TF")
        hist = sum(1 for m in self._models.values() if m.model_type == "HISTONE")
        splice = sum(1 for m in self._models.values() if m.model_type == "SPLICE")
        return f"ModelRegistry({tf} TF + {hist} histone + {splice} splice = {len(self)} models)"


